#!/usr/bin/env python3
"""schema_to_tex.py: render the evidence-manifest JSON Schema as LaTeX tables (report Appendix A),
so that the report and the machine-readable specification can never drift apart."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = json.loads((ROOT / "spec" / "evidence-manifest.schema.json").read_text())
EVENT = json.loads((ROOT / "spec" / "custody-event.schema.json").read_text())
OUT = ROOT / "report" / "generated" / "spec_tables.tex"
DEFS = SCHEMA["$defs"]

CLASS_DEFS = [
    ("SCENE_PHOTOGRAPH", "attrs_scene_photograph"), ("AV_RECORDING", "attrs_av_recording"),
    ("CCTV_EXPORT", "attrs_cctv_export"), ("PHYSICAL_DOCUMENT", "attrs_physical_document"),
    ("PHYSICAL_ITEM", "attrs_physical_item"), ("BIO_TRACE_SAMPLE", "attrs_bio_trace_sample"),
    ("DIGITAL_DEVICE", "attrs_digital_device"), ("FORENSIC_IMAGE", "attrs_forensic_image"),
    ("MOBILE_EXTRACTION", "attrs_mobile_extraction"), ("CLOUD_DATA", "attrs_cloud_data"),
    ("IOT_LOG", "attrs_iot_log"), ("PROCEDURAL_DOCUMENT", "attrs_procedural_document"),
]


def esc(s: str) -> str:
    rep = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}", "<": r"\textless{}",
           ">": r"\textgreater{}", "±": r"$\pm$"}
    return "".join(rep.get(c, c) for c in s)


def typ(p: dict) -> str:
    if "$ref" in p:
        name = p["$ref"].split("/")[-1]
        return {"timestamp": "timestamp", "decimal": "decimal string", "hex256": "hex (64)", "quantity": "quantity",
                "person": "person", "location": "location", "capture_device": "device"}.get(name, name)
    if "enum" in p:
        vals = [str(v) for v in p["enum"]]
        return "one of: " + ", ".join(vals) if len(", ".join(vals)) < 140 else "enum (" + str(len(vals)) + " values)"
    if "const" in p:
        return f"= {p['const']}"
    t = p.get("type")
    if isinstance(t, list):
        t = "/".join(t)
    if t == "array":
        it = p.get("items", {})
        return "list of " + typ(it) if it else "list"
    if t == "object" and "properties" in p:
        return "object{" + ", ".join(p["properties"]) + "}"
    return t or "any"


def table(title: str, d: dict) -> str:
    req = set(d.get("required", []))
    rows = []
    for k, p in d.get("properties", {}).items():
        desc = p.get("description", "")
        if "$ref" in p and not desc:
            desc = DEFS.get(p["$ref"].split("/")[-1], {}).get("description", "")
        rows.append(f"\\texttt{{{esc(k)}}} & {'\\textbf{yes}' if k in req else 'no'} & {esc(typ(p))} & {esc(desc)}\\\\")
    return "\n".join([
        f"\\subsubsection*{{{esc(title)}}}",
        r"\begin{longtable}{@{}p{0.24\linewidth}p{0.07\linewidth}p{0.27\linewidth}p{0.36\linewidth}@{}}",
        r"\toprule Field & Req. & Type / allowed values & Meaning\\ \midrule\endhead",
        *rows, r"\bottomrule", r"\end{longtable}", ""])


parts = [r"% Generated by outputs/tools/schema_to_tex.py from outputs/spec/*.schema.json -- do not edit by hand.",
         r"\subsection{Common blocks (all evidence classes)}"]
top = {k: v for k, v in SCHEMA.items() if k in ("properties", "required")}
parts.append(table("Manifest (top level)", top))
for name, title in [("case", "case"), ("collection", "collection"), ("packaging", "packaging"),
                    ("artefact", "artefacts[] (one per captured file)"), ("capture_device", "capture_device (mirrors the BSA s.63(4)(c) Schedule)"),
                    ("person", "person"), ("identity_fingerprint", "identity_fingerprints[]")]:
    parts.append(table(title, DEFS[name]))
parts.append(r"\subsection{Class-specific attributes (\texttt{class\_attributes})}")
for cls, d in CLASS_DEFS:
    parts.append(table(cls, DEFS[d]))
parts.append(r"\subsection{Custody event}")
parts.append(table("custody event (submitted to the chaincode)", {k: v for k, v in EVENT.items() if k in ("properties", "required")}))
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(parts) + "\n")
print(f"wrote {OUT}")
